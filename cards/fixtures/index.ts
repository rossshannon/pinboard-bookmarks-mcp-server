/**
 * Every card's fixtures, keyed by the card's `ui://` name and then by
 * scenario. Each is a whole tool result as a host delivers it: a success
 * carries `structuredContent`, a failure `isError` and its text, so the same
 * entry drives the jsdom suites, the browser checks and the capture gallery.
 *
 * Kept as JSON so the Python suite can read them too, and check that what
 * the cards are tested against is what the tools actually return.
 */

import type { CardToolResultLike } from '../src/shell/use-card-result.ts'

import bookmarks from './bookmarks.json' with { type: 'json' }
import previews from './previews.json' with { type: 'json' }
import tags from './tags.json' with { type: 'json' }

export type FixtureSet = Readonly<Record<string, CardToolResultLike>>

export const CARD_FIXTURES: Readonly<Record<'bookmarks' | 'tags', FixtureSet>> = { bookmarks, tags }

/** One fixture's `structuredContent`, for the jsdom suites, which render a card component directly. */
export const fixtureData = (card: keyof typeof CARD_FIXTURES, scenario: string): Record<string, unknown> => {
  const result = CARD_FIXTURES[card][scenario]
  if (result === undefined) throw new Error(`no ${card} fixture named ${scenario}`)
  return result.structuredContent ?? {}
}

/** One fixture's failure, for the error scenarios. */
export const fixtureError = (card: keyof typeof CARD_FIXTURES, scenario: string): { text: string } => {
  const result = CARD_FIXTURES[card][scenario]
  const text = result?.content?.[0]?.text
  if (result?.isError !== true || typeof text !== 'string') throw new Error(`${card} fixture ${scenario} is not a failure`)
  return { text }
}

/**
 * `get_link_previews` results, by scenario: what the app-only tool answers
 * when the bookmarks card asks about the rows of the `rich` and `rich-many`
 * fixtures. Generated by `scripts/make-preview-fixtures.ts`, images and all.
 * `hostile` is deliberately not a shape the server sends.
 */
export const PREVIEW_FIXTURES = previews as unknown as Readonly<Record<PreviewScenario, CardToolResultLike>>

export type PreviewScenario = 'busy' | 'hostile' | 'mixed' | 'ok' | 'rate-limited'

/**
 * Which preview scenarios each bookmarks fixture is captured and checked
 * with, beside the plain render on a host that cannot call tools at all.
 */
export const PREVIEW_RUNS: Readonly<Record<string, readonly PreviewScenario[]>> = {
  'rich': ['ok', 'mixed', 'hostile', 'rate-limited', 'busy'],
  'rich-many': ['ok'],
}

/** One preview fixture's `structuredContent`. */
export const previewData = (scenario: PreviewScenario): Record<string, unknown> => PREVIEW_FIXTURES[scenario].structuredContent ?? {}

/**
 * What the tool would answer for exactly these URLs, from a fixture: its
 * entries for them in the order asked, and "no data" for any it lacks.
 */
export const answerPreviews = (scenario: PreviewScenario, urls: readonly string[]): Record<string, unknown> => {
  const data = previewData(scenario)
  // A server that sanitises nothing does not mind what it was asked either.
  if (scenario === 'hostile') return data
  const entries = (data['previews'] ?? []) as ReadonlyArray<{ readonly status?: unknown, readonly url?: unknown }>
  const answered = urls.map(url => entries.find(entry => entry.url === url) ?? { status: 'no_data', url })
  const limited = answered.some(entry => entry.status === 'rate_limited')
  return limited ? { previews: answered, retry_after_seconds: data['retry_after_seconds'] } : { previews: answered }
}
